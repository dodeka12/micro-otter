"""The device log prefix taxonomy must stay identical everywhere it is declared.

A device log line is classified by its leading ``[level]`` tag. Four things have
to agree, or lines silently disappear into the ``raw`` bucket instead of landing
in the filter the user selected:

* ``PLAIN_LEVELS`` in ``tools/runtime_log.py`` -- what the device may emit,
* ``LOG_PREFIXES`` in ``serial/device-connection.ts`` -- what the host parses,
* ``MessageType`` in ``serial/device-connection.ts`` -- what reaches the view,
* the filter set of ``views/console-log-view.ts`` -- what the user can select.

See ``docs/dev/device-communication/log-prefix-conventions.md``.
"""

import ast
import importlib.util
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
DEVICE_ROOT = REPO_ROOT / "src" / "micro_otter" / "nodes" / "device"
TYPESCRIPT_ROOT = REPO_ROOT / "src" / "micro_otter" / "nodes" / "html" / "js"
RUNTIME_LOG_PATH = DEVICE_ROOT / "tools" / "runtime_log.py"
DEVICE_CONNECTION_PATH = TYPESCRIPT_ROOT / "serial" / "device-connection.ts"
CONSOLE_LOG_VIEW_PATH = TYPESCRIPT_ROOT / "views" / "console-log-view.ts"

#: The taxonomy itself: every tag a device log line may carry. ``raw`` is the
#: bucket for everything else, so it is not a prefix.
CANONICAL_PREFIXES = ("user", "system", "otter", "info", "warning", "error", "success", "data")

#: Levels ``tools.runtime_log.log_plain()`` may emit. ``user`` is excluded: user
#: code is generated by the collection, not by the runtime shell.
RUNTIME_LEVELS = tuple(level for level in CANONICAL_PREFIXES if level != "user")

#: Sources whose console lines are device runtime output and are therefore
#: required to use a canonical prefix.
SCANNED_SOURCES = (
    DEVICE_ROOT / "runtime" / "general",
    DEVICE_ROOT / "node_pkgs",
    DEVICE_ROOT / "tools" / "wifi_manager.py",
    REPO_ROOT / "src" / "micro_otter" / "tools" / "firmware_compile" / "runtime_assets",
)

#: Not runtime output: vendored MicroPython code that logs in its own format, and
#: REPL-only diagnostic tools whose output is read by the person typing at the
#: console (``tools/wifi_diag.py``, ``tools/wifi_probe.py``, ...).
SCAN_EXCLUDED_PARTS = ("node_pkgs/mqtt/otter_mqtt/umqtt",)

_TAG_PATTERN = re.compile(r"\[([A-Za-z0-9][A-Za-z0-9_/-]*)\]")


def _source(path):
    return path.read_text(encoding="utf-8")


def _ts_string_list(path, name):
    """Values of ``export const <name> = Object.freeze([...]);``."""
    body = re.search(
        rf"export const {re.escape(name)} = Object\.freeze\(\[(.*?)\]\);",
        _source(path),
        re.S,
    )
    assert body is not None, f"{name} not found in {path.name}"
    return re.findall(r"'([^']+)'", body.group(1))


def _ts_enum_values(path, name):
    """Values of ``export const <name> = Object.freeze({ KEY: 'value', ... });``."""
    body = re.search(
        rf"export const {re.escape(name)} = Object\.freeze\(\{{(.*?)\}}\);",
        _source(path),
        re.S,
    )
    assert body is not None, f"{name} not found in {path.name}"
    return dict(re.findall(r"([A-Z_]+):\s*'([^']+)'", body.group(1)))


def _load_runtime_log():
    spec = importlib.util.spec_from_file_location("device_runtime_log", RUNTIME_LOG_PATH)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def _leading_tag(literal):
    """The ``[tag]`` a string literal starts with, if it starts with one."""
    match = _TAG_PATTERN.match(literal)
    return match.group(1) if match else None


def _scanned_files():
    for root in SCANNED_SOURCES:
        candidates = [root] if root.is_file() else sorted(root.rglob("*.py"))
        for path in candidates:
            relative = path.relative_to(REPO_ROOT).as_posix()
            if any(part in relative for part in SCAN_EXCLUDED_PARTS):
                continue
            yield path


def _tagged_literals(path):
    """Every string literal of *path* that starts with a bracket tag."""
    for node in ast.walk(ast.parse(_source(path))):
        literals = []
        if isinstance(node, ast.JoinedStr):
            first = node.values[0] if node.values else None
            if isinstance(first, ast.Constant) and isinstance(first.value, str):
                literals.append(first.value)
        elif isinstance(node, ast.Constant) and isinstance(node.value, str):
            literals.append(node.value)
        for literal in literals:
            tag = _leading_tag(literal)
            if tag is not None:
                yield tag, literal.splitlines()[0]


_LEVEL_FUNCTIONS = ("_log", "_emit", "log_plain")


def _level_arguments(path):
    """Literal levels passed to the device's ``_log(level, ...)`` style helpers."""
    for node in ast.walk(ast.parse(_source(path))):
        if not isinstance(node, ast.Call) or not node.args:
            continue
        func = node.func
        name = getattr(func, "id", None) or getattr(func, "attr", None)
        if name not in _LEVEL_FUNCTIONS:
            continue
        first = node.args[0]
        if isinstance(first, ast.Constant) and isinstance(first.value, str):
            yield first.value, f"{name}()"


def test_device_levels_match_the_canonical_taxonomy():
    runtime_log = _load_runtime_log()
    levels = tuple(runtime_log.PLAIN_LEVELS)

    assert len(levels) == len(set(levels)), "duplicate level in PLAIN_LEVELS"
    assert set(levels) == set(RUNTIME_LEVELS)


def test_host_parses_exactly_the_canonical_taxonomy():
    prefixes = tuple(_ts_string_list(DEVICE_CONNECTION_PATH, "LOG_PREFIXES"))

    assert len(prefixes) == len(set(prefixes)), "duplicate prefix in LOG_PREFIXES"
    assert set(prefixes) == set(CANONICAL_PREFIXES)


def test_host_message_types_are_the_prefixes_plus_raw():
    values = set(_ts_enum_values(DEVICE_CONNECTION_PATH, "MessageType").values())

    assert values == set(CANONICAL_PREFIXES) | {"raw"}


def test_console_filters_are_the_prefixes_plus_raw():
    view_path = CONSOLE_LOG_VIEW_PATH
    enum_values = _ts_enum_values(view_path, "MessageType")
    body = re.search(
        r"const DEFAULT_MESSAGE_TYPES: MessageTypeMap = \{(.*?)\n\};",
        _source(view_path),
        re.S,
    )
    assert body is not None, f"DEFAULT_MESSAGE_TYPES not found in {view_path.name}"

    registered = {
        enum_values[key] for key in re.findall(r"id:\s*MessageType\.([A-Z_]+)", body.group(1))
    }
    assert registered == set(CANONICAL_PREFIXES) | {"raw"}


@pytest.mark.parametrize("level", ["debug", "trace", "", None])
def test_unknown_plain_level_falls_back_to_info(level, capsys):
    runtime_log = _load_runtime_log()

    runtime_log.log_plain(level, "demo", "message")

    assert capsys.readouterr().out == "[info] demo: message\n"


def test_plain_log_line_carries_the_level_and_source(capsys):
    runtime_log = _load_runtime_log()

    runtime_log.log_plain("error", "controller", "main loop raised")

    assert capsys.readouterr().out == "[error] controller: main loop raised\n"


def test_device_runtime_sources_only_emit_canonical_prefixes():
    violations = []
    for path in _scanned_files():
        relative = path.relative_to(REPO_ROOT).as_posix()
        for tag, literal in _tagged_literals(path):
            if tag not in CANONICAL_PREFIXES:
                violations.append(f"{relative}: [{tag}] in {literal!r}")
        for level, call in _level_arguments(path):
            if level not in RUNTIME_LEVELS:
                violations.append(f"{relative}: {level!r} passed to {call}")

    assert not violations, "non-canonical device log prefix(es):\n" + "\n".join(violations)


def test_device_runtime_scan_actually_finds_tagged_lines():
    """Guard against the scan silently going empty and passing vacuously."""

    files = list(_scanned_files())
    tagged = [path for path in files if list(_tagged_literals(path))]
    levelled = [path for path in files if list(_level_arguments(path))]

    assert len(files) > 40
    assert len(tagged) > 15
    assert len(levelled) > 3
