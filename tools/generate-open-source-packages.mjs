import fs from 'fs';
import path from 'path';

const ROOT = process.cwd();

const PATHS = {
    packageJson: path.join(ROOT, 'package.json'),
    indexHtml: path.join(ROOT, 'src', 'micro_otter', 'nodes', 'index.html'),
    overrides: path.join(ROOT, 'tools', 'open-source-package-overrides.json'),
    output: path.join(
        ROOT,
        'src',
        'micro_otter',
        'nodes',
        'html',
        'js',
        'core',
        'open-source-packages.generated.js'
    ),
};

function readJson(filePath) {
    return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

function collectRuntimeWebPackages(packageJson) {
    const names = new Set();

    Object.keys(packageJson.dependencies || {}).forEach((packageName) => {
        names.add(packageName);
    });

    return names;
}

function collectCdnPackages(indexHtmlSource) {
    const names = new Set();
    const cdnRegex = /cdn\.jsdelivr\.net\/npm\/((?:@[^@\/\s]+\/)?[^@\/\s]+)@/g;

    for (const match of indexHtmlSource.matchAll(cdnRegex)) {
        if (match[1]) {
            names.add(match[1]);
        }
    }

    return names;
}

/**
 * Collect the icon/asset sets that are vendored as loose files instead of being installed as an
 * npm package or loaded from a CDN. The dependency scan above cannot see them, but they still
 * need a licence row in the About dialog — the Google Material Symbols SVGs under `html/icons/`
 * and `node_pkgs/<package>/icons/` are the current case.
 * @param {object} overrides - Parsed contents of tools/open-source-package-overrides.json.
 * @returns {{name: string, license: string, url: string}[]} Validated vendored asset entries.
 */
function collectVendoredAssets(overrides) {
    const assets = overrides.vendoredAssets;

    if (assets === undefined) {
        return [];
    }

    if (!Array.isArray(assets)) {
        throw new Error(
            '"vendoredAssets" in tools/open-source-package-overrides.json must be an array of { name, license, url } entries.'
        );
    }

    return assets.map((asset, index) => {
        if (!asset || !asset.name || !asset.license || !asset.url) {
            throw new Error(
                `Vendored asset #${index} in tools/open-source-package-overrides.json needs "name", "license" and "url".`
            );
        }

        return { name: asset.name, license: asset.license, url: asset.url };
    });
}

function formatGeneratedSource(entries) {
    const lines = [];
    lines.push('// Copyright (c) 2025 Christian Perwass; SPDX-License-Identifier: GPL-3.0-only');
    lines.push('// This file is auto-generated by tools/generate-open-source-packages.mjs');
    lines.push('// Do not edit by hand. Update tools/open-source-package-overrides.json and rerun generator.');
    lines.push('');
    lines.push('/** @type {{name: string, license: string, url: string}[]} */');
    lines.push('export const OPEN_SOURCE_PACKAGES = [');

    entries.forEach((entry) => {
        lines.push(
            `    { name: ${JSON.stringify(entry.name)}, license: ${JSON.stringify(entry.license)}, url: ${JSON.stringify(entry.url)} },`
        );
    });

    lines.push('];');
    lines.push('');
    return `${lines.join('\n')}`;
}

function main() {
    const packageJson = readJson(PATHS.packageJson);
    const indexHtmlSource = fs.readFileSync(PATHS.indexHtml, 'utf-8');
    const overrides = readJson(PATHS.overrides);

    const packageIds = new Set();
    [...collectRuntimeWebPackages(packageJson), ...collectCdnPackages(indexHtmlSource)].forEach(
        (packageId) => packageIds.add(packageId)
    );

    const missingOverrides = [];
    const packageEntries = Array.from(packageIds)
        .sort((a, b) => a.localeCompare(b))
        .map((packageId) => {
            const override = overrides[packageId];
            if (!override || !override.license || !override.url) {
                missingOverrides.push(packageId);
                return null;
            }

            return {
                id: packageId,
                name: override.name || packageId,
                license: override.license,
                url: override.url,
            };
        })
        .filter(Boolean)
        .sort((a, b) => a.name.localeCompare(b.name));

    if (missingOverrides.length > 0) {
        const message = [
            'Missing OSS overrides for the following packages:',
            ...missingOverrides.map((name) => `- ${name}`),
            '',
            'Add entries in tools/open-source-package-overrides.json with:',
            '{ "name": "Display Name", "license": "SPDX", "url": "https://github.com/..." }',
        ].join('\n');

        throw new Error(message);
    }

    // Vendored asset sets are merged only after the override check, so a missing package override
    // still fails loudly. On a display-name clash the npm/CDN row wins and the vendored one is
    // dropped, because both would render the same About-dialog label.
    const vendoredAssets = collectVendoredAssets(overrides);
    const seenNames = new Set(packageEntries.map((entry) => entry.name.toLowerCase()));
    const entries = [...packageEntries];

    vendoredAssets.forEach((asset) => {
        const nameKey = asset.name.toLowerCase();
        if (seenNames.has(nameKey)) {
            return;
        }

        seenNames.add(nameKey);
        entries.push(asset);
    });

    entries.sort((a, b) => a.name.localeCompare(b.name));

    const outputSource = formatGeneratedSource(entries);
    fs.writeFileSync(PATHS.output, outputSource, 'utf-8');

    console.log(
        `Generated ${path.relative(ROOT, PATHS.output)} with ${entries.length} open-source entries ` +
            `(${packageEntries.length} from package.json/CDN, ${vendoredAssets.length} vendored asset sets).`
    );
}

main();
